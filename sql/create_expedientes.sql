-- Esquema inicial del prototipo para relacionar solicitantes, expedientes y predios.
-- Ejecutar una sola vez en la base sigep con un usuario administrador.

CREATE SEQUENCE IF NOT EXISTS public.expedientes_folio_seq;

CREATE TABLE IF NOT EXISTS public.solicitantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  identificacion TEXT,
  telefono TEXT,
  correo TEXT,
  domicilio_notificacion TEXT,
  representante_nombre TEXT,
  representante_identificacion TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT solicitantes_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS public.expedientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio TEXT NOT NULL UNIQUE,
  tipo_tramite TEXT NOT NULL CHECK (tipo_tramite IN (
    'titulacion',
    'certificacion_antecedentes_titulo',
    'certificacion_copia_titulo',
    'constancia_datos_lote',
    'constancia_tramite_titulo'
  )),
  fecha_recepcion DATE NOT NULL DEFAULT CURRENT_DATE,
  estado TEXT NOT NULL DEFAULT 'recibido' CHECK (estado IN (
    'recibido', 'en_revision', 'prevenido', 'en_proceso', 'listo_para_entrega', 'entregado', 'no_procede', 'cerrado'
  )),
  etapa_actual TEXT NOT NULL DEFAULT 'recepcion',
  area_responsable TEXT NOT NULL DEFAULT 'Ventanilla',
  solicitante_id BIGINT NOT NULL REFERENCES public.solicitantes(id) ON DELETE RESTRICT,
  observaciones TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.expediente_predios (
  expediente_id BIGINT NOT NULL REFERENCES public.expedientes(id) ON DELETE RESTRICT,
  predio_id BIGINT NOT NULL REFERENCES public.predios(id) ON DELETE RESTRICT,
  PRIMARY KEY (expediente_id, predio_id)
);

CREATE TABLE IF NOT EXISTS public.movimientos_expediente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expediente_id BIGINT NOT NULL REFERENCES public.expedientes(id) ON DELETE RESTRICT,
  etapa_origen TEXT,
  etapa_destino TEXT NOT NULL,
  estado TEXT NOT NULL,
  area_origen TEXT,
  area_destino TEXT,
  actor TEXT,
  observaciones TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_expedientes_folio ON public.expedientes (folio);
CREATE INDEX IF NOT EXISTS idx_expedientes_fecha_recepcion ON public.expedientes (fecha_recepcion);
CREATE INDEX IF NOT EXISTS idx_expedientes_estado_etapa ON public.expedientes (estado, etapa_actual);
CREATE INDEX IF NOT EXISTS idx_expediente_predios_predio ON public.expediente_predios (predio_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_expediente_fecha ON public.movimientos_expediente (expediente_id, created_at DESC);

GRANT CONNECT ON DATABASE sigep TO sigep_editor;
GRANT USAGE ON SCHEMA public TO sigep_editor;
GRANT SELECT, INSERT ON TABLE public.solicitantes, public.expedientes,
  public.expediente_predios, public.movimientos_expediente TO sigep_editor;
GRANT USAGE, SELECT ON SEQUENCE public.expedientes_folio_seq TO sigep_editor;

DO $$
DECLARE
  nombre_tabla TEXT;
  nombre_secuencia TEXT;
BEGIN
  FOREACH nombre_tabla IN ARRAY ARRAY['solicitantes', 'expedientes', 'movimientos_expediente'] LOOP
    nombre_secuencia := pg_get_serial_sequence('public.' || nombre_tabla, 'id');
    IF nombre_secuencia IS NOT NULL THEN
      EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO sigep_editor', nombre_secuencia::regclass);
    END IF;
  END LOOP;
END
$$;
