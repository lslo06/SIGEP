-- Historial de correcciones geométricas de los predios.
-- Ejecutar una sola vez en la base sigep como sigep_admin.

CREATE TABLE IF NOT EXISTS public.predio_geometria_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  predio_id BIGINT NOT NULL REFERENCES public.predios(id) ON DELETE RESTRICT,
  clave_catastral TEXT NOT NULL,
  geom_anterior public.geometry(MultiPolygon, 4326) NOT NULL,
  geom_nueva public.geometry(MultiPolygon, 4326) NOT NULL,
  superficie_anterior NUMERIC(14, 2),
  superficie_nueva NUMERIC(14, 2) NOT NULL CHECK (superficie_nueva >= 0),
  actor TEXT NOT NULL CHECK (length(trim(actor)) > 0),
  motivo TEXT NOT NULL CHECK (length(trim(motivo)) > 0),
  fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_predio_geometria_historial_predio_fecha
  ON public.predio_geometria_historial (predio_id, fecha_cambio DESC);

GRANT SELECT, INSERT ON TABLE public.predio_geometria_historial TO sigep_editor;
GRANT UPDATE (geom, superficie) ON TABLE public.predios TO sigep_editor;

DO $$
DECLARE
  history_sequence TEXT;
BEGIN
  history_sequence := pg_get_serial_sequence('public.predio_geometria_historial', 'id');
  IF history_sequence IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO sigep_editor', history_sequence::regclass);
  END IF;
END
$$;
